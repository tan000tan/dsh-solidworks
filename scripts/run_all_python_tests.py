"""严格执行 tests/*_test.py 全量 Python 测试套件聚合器 (G-03 / TEST-AGGREGATOR)。

约束：
1. 自动发现 `tests/*_test.py`，禁止遗漏新增测试文件。
2. 严禁将 `Ran 0 tests`、`skipped > 0` 或非零退出码静默统计为 PASS。
3. 默认输出写入系统临时目录或 `--out` 指定路径，严禁在源码树 `src/audit/` 下写入工作区污染产物。
4. 任一套件失败、空跑或跳过时返回非零退出码。
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

sys.dont_write_bytecode = True

_RAN_RE = re.compile(r"Ran\s+(\d+)\s+tests?", re.IGNORECASE)
_SKIP_RE = re.compile(r"skipped=(\d+)", re.IGNORECASE)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Run all Python test suites strictly.")
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(tempfile.gettempdir()) / "dsh-solidworks-python-tests-summary.json",
        help="Output JSON report path (defaults outside plugin source tree).",
    )
    parser.add_argument(
        "--python",
        type=str,
        default=os.environ.get("DSH_SOLIDWORKS_PYTHON", sys.executable),
        help="Python interpreter path.",
    )
    args = parser.parse_args(argv)

    plugin_root = Path(__file__).resolve().parent.parent
    tests_dir = plugin_root / "tests"
    python_test_files = sorted(p.name for p in tests_dir.glob("*_test.py"))

    env = os.environ.copy()
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env["PYTHONUTF8"] = "1"
    env["PYTHONIOENCODING"] = "utf-8"
    python_exe = args.python
    env["DSH_SOLIDWORKS_PYTHON"] = python_exe

    results: dict[str, dict] = {}
    total_pass = 0
    total_fail = 0
    total_skip = 0

    print(f"=== EXECUTING ALL {len(python_test_files)} PYTHON TEST SUITES ===")

    for tfile in python_test_files:
        tpath = tests_dir / tfile
        if not tpath.exists():
            print(f"  [MISSING] {tfile}")
            results[tfile] = {"status": "MISSING", "code": -1, "ran": 0, "skipped": 0, "output": ""}
            total_fail += 1
            continue

        t0 = time.time()
        cmd = [python_exe, "-B", str(tpath)]
        try:
            proc = subprocess.run(
                cmd,
                env=env,
                cwd=str(plugin_root),
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                timeout=450,
            )
            duration = time.time() - t0
            out = (proc.stdout or "") + "\n" + (proc.stderr or "")
            ran_matches = [int(m.group(1)) for m in _RAN_RE.finditer(out)]
            skip_matches = [int(m.group(1)) for m in _SKIP_RE.finditer(out)]
            ran_count = sum(ran_matches) if ran_matches else None
            skipped_count = sum(skip_matches)

            if proc.returncode != 0:
                status = "FAIL"
                total_fail += 1
                print(f"  [FAIL] {tfile} (exit {proc.returncode}, {duration:.2f}s)")
            elif ran_count is not None and ran_count == 0:
                status = "EMPTY"
                total_fail += 1
                print(f"  [EMPTY] {tfile} (Ran 0 tests, {duration:.2f}s)")
            elif skipped_count > 0:
                status = "SKIPPED"
                total_skip += 1
                print(f"  [SKIPPED] {tfile} (skipped={skipped_count}, {duration:.2f}s)")
            else:
                status = "PASS"
                total_pass += 1
                print(f"  [PASS] {tfile} ({duration:.2f}s)")

            results[tfile] = {
                "status": status,
                "code": proc.returncode,
                "ran": ran_count,
                "skipped": skipped_count,
                "duration": round(duration, 4),
                "output": out,
            }
        except subprocess.TimeoutExpired:
            duration = time.time() - t0
            results[tfile] = {"status": "TIMEOUT", "code": -1, "ran": 0, "skipped": 0, "duration": duration, "output": "Timed out after 450s"}
            total_fail += 1
            print(f"  [TIMEOUT] {tfile} ({duration:.2f}s)")
        except Exception as exc:
            results[tfile] = {"status": "ERROR", "code": -2, "ran": 0, "skipped": 0, "duration": 0, "output": str(exc)}
            total_fail += 1
            print(f"  [ERROR] {tfile}: {exc}")

    print("\n==========================================")
    print("=== ALL TEST SUITES EXECUTION COMPLETED ===")
    print(f"=== PASSED:  {total_pass} / {len(python_test_files)}")
    print(f"=== SKIPPED: {total_skip} / {len(python_test_files)}")
    print(f"=== FAILED:  {total_fail} / {len(python_test_files)}")
    print("==========================================")

    # Remove any accidental __pycache__ or *.pyc generated by child processes
    for cache_dir in list(plugin_root.rglob("__pycache__")):
        shutil.rmtree(cache_dir, ignore_errors=True)
    for pyc_file in list(plugin_root.rglob("*.pyc")):
        pyc_file.unlink(missing_ok=True)

    out_path = Path(args.out).resolve()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    summary_payload = {
        "total_suites": len(python_test_files),
        "passed": total_pass,
        "skipped": total_skip,
        "failed": total_fail,
        "results": results,
    }
    out_path.write_text(json.dumps(summary_payload, indent=2, ensure_ascii=False), encoding="utf-8")
    return 1 if (total_fail > 0 or total_skip > 0) else 0


if __name__ == "__main__":
    raise SystemExit(main())
